import React, { useState } from 'react';
import { TrendingUp, Edit2, Info, ArrowUpRight, Check, X, ShieldAlert } from 'lucide-react';
import { AdminProduct } from '../../types';
import { formatPrice } from '../../utils/currency';
import { updateProduct } from '../../services/adminService';

interface AdminPricingMarginsProps {
  products: AdminProduct[];
  onRefresh: () => void;
}

export const AdminPricingMargins: React.FC<AdminPricingMarginsProps> = ({
  products,
  onRefresh,
}) => {
  const [editingProduct, setEditingProduct] = useState<AdminProduct | null>(null);
  const [costs, setCosts] = useState({
    selling_price: 399,
    material_cost: 140,
    packaging_cost: 35,
    other_variable_cost: 15,
  });

  const handleOpenEdit = (p: AdminProduct) => {
    setEditingProduct(p);
    setCosts({
      selling_price: p.selling_price,
      material_cost: p.material_cost || 0,
      packaging_cost: p.packaging_cost || 0,
      other_variable_cost: p.other_variable_cost || 0,
    });
  };

  const handleSaveCosts = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!editingProduct) return;
    try {
      await updateProduct(editingProduct.id, {
        selling_price: Number(costs.selling_price),
        material_cost: Number(costs.material_cost),
        packaging_cost: Number(costs.packaging_cost),
        other_variable_cost: Number(costs.other_variable_cost),
      });
      setEditingProduct(null);
      onRefresh();
    } catch (err) {
      alert('Failed to update product costs');
    }
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="text-2xl sm:text-3xl font-black text-brand-ink tracking-tight font-display">
          Product Pricing &amp; Unit Economics
        </h1>
        <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
          Internal cost modeling, kit contribution, and pricing assumptions.
        </p>
      </div>

      {/* Accounting Clarification Notice (Section 9 Requirement) */}
      <div className="p-4 rounded-2xl bg-teal-50/70 border border-teal-200/70 text-brand-teal text-xs flex items-start gap-3">
        <Info className="w-5 h-5 text-brand-teal shrink-0 mt-0.5" />
        <div className="space-y-1">
          <p className="font-bold text-slate-800">
            Internal Costing Principles: Contribution ≠ Net Profit
          </p>
          <p className="text-slate-600 leading-relaxed">
            <strong>Estimated Contribution</strong> represents the gross surplus generated by each kit sold (<code>Selling Price - Total Variable Costs</code>). It covers fixed business expenses such as marketing, domain hosting, storage, and founder time before yielding net business profit. Internal unit costs are strictly protected and never displayed on the public customer site.
          </p>
        </div>
      </div>

      {/* Pricing & Margin Cards Table */}
      <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-slate-200 bg-slate-50/70 text-[11px] font-bold uppercase tracking-wider text-slate-500">
                <th className="py-3 px-4">Celebration Box</th>
                <th className="py-3 px-4">Selling Price</th>
                <th className="py-3 px-4">Material Cost</th>
                <th className="py-3 px-4">Packaging Cost</th>
                <th className="py-3 px-4">Other Variable</th>
                <th className="py-3 px-4">Total Variable Cost</th>
                <th className="py-3 px-4">Est. Contribution</th>
                <th className="py-3 px-4">Contribution Margin</th>
                <th className="py-3 px-4 text-right">Edit Costs</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {products.map((p) => {
                const totalVariableCost =
                  Number(p.material_cost || 0) +
                  Number(p.packaging_cost || 0) +
                  Number(p.other_variable_cost || 0);
                const contribution = Number(p.selling_price || 0) - totalVariableCost;
                const marginPercent =
                  p.selling_price > 0
                    ? ((contribution / p.selling_price) * 100).toFixed(1)
                    : '0';

                return (
                  <tr key={p.id} className="hover:bg-slate-50/50 transition-colors">
                    <td className="py-4 px-4">
                      <div className="font-bold text-slate-800">{p.name}</div>
                      <span className="text-[11px] text-slate-400 font-mono">
                        {p.total_pieces} pieces kit
                      </span>
                    </td>

                    <td className="py-4 px-4 font-black text-brand-pink text-sm">
                      {formatPrice(p.selling_price)}
                    </td>

                    <td className="py-4 px-4 font-medium text-slate-700">
                      {formatPrice(p.material_cost || 0)}
                    </td>

                    <td className="py-4 px-4 font-medium text-slate-700">
                      {formatPrice(p.packaging_cost || 0)}
                    </td>

                    <td className="py-4 px-4 font-medium text-slate-700">
                      {formatPrice(p.other_variable_cost || 0)}
                    </td>

                    <td className="py-4 px-4 font-bold text-slate-600">
                      {formatPrice(totalVariableCost)}
                    </td>

                    <td className="py-4 px-4">
                      <span className="font-black text-brand-teal text-sm">
                        {formatPrice(contribution)}
                      </span>
                      <span className="text-[10px] text-slate-400 block">per kit sold</span>
                    </td>

                    <td className="py-4 px-4">
                      <span className="inline-block px-2.5 py-1 rounded-full text-xs font-black bg-teal-50 text-brand-teal border border-teal-200">
                        {marginPercent}%
                      </span>
                    </td>

                    <td className="py-4 px-4 text-right">
                      <button
                        onClick={() => handleOpenEdit(p)}
                        className="p-1.5 rounded-lg text-slate-400 hover:text-brand-pink hover:bg-slate-100 transition-colors cursor-pointer"
                        title="Update cost assumptions"
                      >
                        <Edit2 className="w-4 h-4" />
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </div>

      {/* EDIT COST ASSUMPTIONS MODAL */}
      {editingProduct && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-brand-ink/60 backdrop-blur-xs">
          <div className="bg-white rounded-2xl shadow-2xl border border-slate-200 w-full max-w-md overflow-hidden">
            <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
              <h2 className="text-sm font-extrabold text-brand-ink">
                Update Pricing &amp; Costs: {editingProduct.name}
              </h2>
              <button
                onClick={() => setEditingProduct(null)}
                className="p-1 rounded text-slate-400 hover:text-slate-700"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <form onSubmit={handleSaveCosts} className="p-6 space-y-4 text-xs">
              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Customer Selling Price (₹) <span className="text-brand-pink">*</span>
                </label>
                <input
                  type="number"
                  min={1}
                  required
                  value={costs.selling_price}
                  onChange={(e) => setCosts({ ...costs, selling_price: Number(e.target.value) })}
                  className="w-full px-3 py-2 rounded-xl border border-slate-200 font-bold text-brand-pink text-sm"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Balloons &amp; Materials Cost (₹)
                </label>
                <input
                  type="number"
                  min={0}
                  value={costs.material_cost}
                  onChange={(e) => setCosts({ ...costs, material_cost: Number(e.target.value) })}
                  className="w-full px-3 py-2 rounded-xl border border-slate-200"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Packaging &amp; Box Cost (₹)
                </label>
                <input
                  type="number"
                  min={0}
                  value={costs.packaging_cost}
                  onChange={(e) => setCosts({ ...costs, packaging_cost: Number(e.target.value) })}
                  className="w-full px-3 py-2 rounded-xl border border-slate-200"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  Adhesive &amp; Other Variable Cost (₹)
                </label>
                <input
                  type="number"
                  min={0}
                  value={costs.other_variable_cost}
                  onChange={(e) =>
                    setCosts({ ...costs, other_variable_cost: Number(e.target.value) })
                  }
                  className="w-full px-3 py-2 rounded-xl border border-slate-200"
                />
              </div>

              <div className="p-3 rounded-xl bg-slate-50 border border-slate-200 space-y-1">
                <div className="flex justify-between text-slate-500">
                  <span>Total Variable Cost:</span>
                  <span className="font-bold text-slate-800">
                    {formatPrice(
                      costs.material_cost + costs.packaging_cost + costs.other_variable_cost
                    )}
                  </span>
                </div>
                <div className="flex justify-between text-brand-teal font-extrabold text-sm pt-1 border-t border-slate-200/60">
                  <span>Estimated Contribution:</span>
                  <span>
                    {formatPrice(
                      costs.selling_price -
                        (costs.material_cost +
                          costs.packaging_cost +
                          costs.other_variable_cost)
                    )}
                  </span>
                </div>
              </div>

              <div className="pt-3 border-t border-slate-100 flex justify-end gap-2.5">
                <button
                  type="button"
                  onClick={() => setEditingProduct(null)}
                  className="px-4 py-2 rounded-xl border border-slate-200 font-bold text-slate-600 hover:bg-slate-50"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-xl bg-brand-pink text-white font-bold hover:bg-brand-pink-hover shadow-xs"
                >
                  Save Economics
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
